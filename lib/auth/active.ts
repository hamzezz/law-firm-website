/**
 * الحساب الموقوف: `users.is_active = false`.
 *
 * العمود موجود في قاعدة البيانات منذ البداية، ولم يكن في المشروع سطرٌ
 * واحد يقرأه. فمن ينظر إلى الجدول يظنّ أن `is_active = false` يمنع
 * الدخول، ولا يمنع شيئاً — عمودٌ يكذب، وهذا أخطر من عمودٍ ناقص.
 *
 * وهو البديل المهنيّ عن حذف الحساب: يُوقَف الدخول، ويبقى ملفّ القضية.
 *
 * القاعدة المقصودة هنا: لا يُمنع إلا من كانت قيمته `false` صراحةً.
 * فإن جاء الصفّ فارغاً، أو القيمة `null`، أو تعذّر الاستعلام — مضى
 * الحساب كما كان. لأن خطأً تقنياً لا يجوز أن يُقفل محامياً خارج ملفّ
 * قضيّته صباحَ جلسة.
 */
export function isSuspended(row: { is_active?: boolean | null } | null | undefined): boolean {
  if (!row) return false
  return row.is_active === false
}

