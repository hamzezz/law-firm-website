import { dayMonthYear } from '@/lib/text/arabic'

/**
 * عنوان الجلسة المخزَّن.
 *
 * كان «الجلسة رقم N»، والـ N يأتي من عمود `session_order` الذي يُكتب من
 * أربعة مواضع لا يعرف بعضها بعضاً — فتكرّرت أرقامه واختلّ تسلسله. ولذلك
 * صار الترقيم المعروض يُحسب من التاريخ في الصفحات كلّها، وبقي العمود
 * والعنوان يحملان رقماً لا يُعتدّ به.
 *
 * فصار العنوان من التاريخ: حقيقةٌ لا تكذب ولا تحتاج استعلاماً يسبقها.
 * وهذا يُسقط استعلام «أعلى رقم» من كلّ موضع إنشاء جلسة — ثلاث موجاتٍ
 * كانت تُدفع في كلّ حفظ ولا تُعرض نتيجتها على أحد.
 *
 * والعنوان لا يُعرض في بطاقة الجلسة إطلاقاً — البطاقة تعرض الرقم
 * المحسوب من التاريخ. ولا يظهر هذا النصّ إلا في التقويم حين يتعذّر
 * ضمّ عنوان القضية، وهو احتياطٌ نادر.
 */
export function sessionTitleFor(dateValue: string | Date | null | undefined): string {
  const key = String(dateValue || '').slice(0, 10)
  const pretty = dayMonthYear(key)
  return pretty ? 'جلسة ' + pretty : 'جلسة'
}
