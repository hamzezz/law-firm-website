/**
 * حدود الصفوف وكشف القطع الصامت.
 *
 * كانت استعلامات اللوحات بلا `order` وبلا `limit`. وSupabase تضع سقفاً
 * افتراضياً لعدد الصفوف (ألف في الغالب)، فإذا تجاوزته البيانات أعادت
 * ألفاً **بترتيب غير محدَّد** — أي ألفاً عشوائية. فقد تختفي جلسة الغد
 * وتبقى جلسة من سنتين، ولا رسالة خطأ ولا أثر.
 *
 * وهذا الملفّ لا يرفع السقف — لا نملك رفعه من هنا — بل يفعل أمرين:
 *   ١) يُلزمنا بترتيبٍ صريح، فيصير القطع للأقدم لا للعشوائي
 *   ٢) يُشعل تحذيراً في السجلّ قبل أن يقع القطع، لا بعده
 *
 * والعلاج الحقيقي تقسيمُ الاستعلامات بحيث يجلب كلّ عنصر ما يخصّه.
 * وهذا حارسٌ إلى أن يحين ذلك.
 */

/** حدّ صريح نطلبه. السقف الفعليّ قد يكون أقلّ، وهذا مقصود. */
export const ROW_LIMIT = 5000

/** عتبة التحذير — دون سقف Supabase الافتراضي بقليل */
const WARN_AT = 900

/**
 * يُكتب التحذير في سجلّ الخادم. ولا يُفشل شيئاً ولا يُبطئ شيئاً:
 * قياسُ طولِ مصفوفةٍ في الذاكرة.
 */
export function warnIfNearLimit(label: string, rows: any[] | null | undefined) {
  const n = rows ? rows.length : 0
  if (n >= WARN_AT) {
    console.log(
      '[rows] ⚠️  ' + label + ' أعاد ' + n + ' صفاً — اقترب من سقف الصفوف. ' +
      'البيانات ستُقطَع صامتةً قريباً، والعلاج تقسيم الاستعلام.'
    )
  }
}
